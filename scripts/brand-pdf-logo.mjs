// Converts the colour signature SVG of the KAYAS FLUX trace package (public/brand/svg/kayas-signature-colour.svg) into PDF path
// operators, LOSSLESSLY and without any raster: the SVG's M/L/C/Z commands map one to one onto PDF m/l/c/h, so the header stays sharp at
// any resolution. The result is committed as src/lib/pdf/brand-logo-data.ts (the PDF writer must not parse SVG at run time).
// A test (src/lib/pdf/brand-pdf.test.ts) fails if the committed data no longer matches the SVG. Run: node scripts/brand-pdf-logo.mjs
// The vectors are a TRACE of a raster, not an original master (docs/brand/KAYAS-FLUX-TRACE-README.md).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'public/brand/svg/kayas-signature-colour.svg');
const svg = readFileSync(file, 'utf8');
const [, width, height] = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg);
const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map(([, attrs]) => {
  const fill = /fill="#([0-9A-Fa-f]{6})"/.exec(attrs)[1];
  const d = /\sd="([^"]+)"/.exec(attrs)[1];
  const evenOdd = /fill-rule="evenodd"/.test(attrs);
  const tokens = d.match(/[MLCZ]|-?[\d.]+/g);
  const ops = [];
  let i = 0;
  const need = { M: 2, L: 2, C: 6, Z: 0 };
  while (i < tokens.length) {
    const cmd = tokens[i++];
    if (!(cmd in need)) throw new Error(`unsupported path command ${cmd}`);
    const args = tokens.slice(i, i + need[cmd]);
    i += need[cmd];
    ops.push(`${args.join(' ')} ${{ M: 'm', L: 'l', C: 'c', Z: 'h' }[cmd]}`.trim());
  }
  return {
    fill: [0, 2, 4].map((k) => Number((parseInt(fill.slice(k, k + 2), 16) / 255).toFixed(5))),
    evenOdd,
    ops: ops.join(' '),
  };
});
const sha256 = createHash('sha256').update(readFileSync(file)).digest('hex');
const out = `// GENERATED by scripts/brand-pdf-logo.mjs from public/brand/svg/kayas-signature-colour.svg. Do not edit by hand.
// PDF path operators in the SVG's own coordinate system (y down): draw with a flipping matrix (see PdfDocument.logo).
export const KAYAS_SIGNATURE_PDF = ${JSON.stringify({ width: Number(width), height: Number(height), sourceSha256: sha256, paths }, null, 2)} as const;
`;
writeFileSync(join(root, 'src/lib/pdf/brand-logo-data.ts'), out);
console.log(`wrote src/lib/pdf/brand-logo-data.ts: ${paths.length} paths, ${out.length} bytes`);
